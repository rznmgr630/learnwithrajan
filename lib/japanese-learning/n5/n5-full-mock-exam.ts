const FULL_MOCK_KANJI_PATTERN = new RegExp(
  Object.keys(FULL_MOCK_FURIGANA)
    .sort((a, b) => b.length - a.length)
    .join("|"),
  "g",
);

function withFullMockFurigana(text: string): string {
  return text.replace(FULL_MOCK_KANJI_PATTERN, (kanji) => `{${kanji}|${FULL_MOCK_FURIGANA[kanji]}}`);
}

function mc(
  id: string,
  prompt: string,
  choices: string[],
  correctIndex: number,
  explanation?: string,
): Extract<JapaneseWeeklyTestItem, { kind: "mcq" }> {
  return {
    kind: "mcq",
    id,
    prompt: withFullMockFurigana(prompt),
    choices: choices.map(withFullMockFurigana),
    correctIndex,
    explanation,
  };
}

